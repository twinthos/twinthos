#!/usr/bin/env python3
"""Generate engineered visibility content from user prompts.
Uses the twinnthos-brain/engineered-visibility-strategy.md as a guide.
Each run publishes 1 new blog post answering a ChatGPT-style question.
"""
import os, json, datetime
from pathlib import Path

CONTENT_DIR = Path("/root/twinthos-brain/content-queue")
TRIPLETS_FILE = CONTENT_DIR / "triple.json"

def load_triplets():
    if not TRIPLETS_FILE.exists():
        return []
    with open(TRIPLETS_FILE) as f:
        return json.load(f)

def save_triplets(triplets):
    TRIPLETS_FILE.write_text(json.dumps(triplets, indent=2))

def generate_content(prompt):
    now = datetime.datetime.utcnow().isoformat()
    return f"""# {prompt['title']}

**Updated:** {now}

{prompt['body'][:500]}...

Read the full analysis in the Twinthos Brain.

---
*Generated by engineered visibility pipeline*"""

def main():
    CONTENT_DIR.mkdir(exist_ok=True)
    triplets = load_triplets()
    
    if not triplets:
        print("No content queued")
        return
    
    prompt = triplets.pop(0)
    content = generate_content(prompt)
    
    slug = prompt['title'].lower().replace(' ', '-')
    out_file = f"/var/www/twinthos.com/content/{slug}.md"
    Path(out_file).parent.mkdir(parents=True, exist_ok=True)
    Path(out_file).write_text(content)
    
    save_triplets(triplets)
    print(f"✓ Published: {slug}")

if __name__ == "__main__":
    main()